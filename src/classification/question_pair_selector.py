from __future__ import annotations

from dataclasses import dataclass

from ._llm import LLMCallable, invoke_default_llm, parse_json_response
from .schemas import QuestionSubtypePrediction, QuestionTypePrediction


@dataclass(frozen=True)
class QuestionPairCandidate:
    question_type: QuestionTypePrediction
    question_subtype: QuestionSubtypePrediction

    @property
    def key(self) -> str:
        return f"{self.question_type.code}|{self.question_subtype.code}"


class QuestionPairSelector:
    def __init__(self, llm: LLMCallable | None = None):
        self._llm = llm or invoke_default_llm

    def select(
        self, text: str, candidates: list[QuestionPairCandidate]
    ) -> QuestionPairCandidate:
        if not candidates:
            raise ValueError("Question pair candidates must not be empty")
        if len(candidates) == 1:
            return candidates[0]

        lines = []
        allowed_keys = {candidate.key for candidate in candidates}
        for candidate in candidates:
            question_type = candidate.question_type
            subtype = candidate.question_subtype
            lines.append(
                f"- key={candidate.key}; "
                f"questionType={question_type.code} {question_type.name}; "
                f"questionTypeConfidence={question_type.confidence:.2f}; "
                f"subtype={subtype.code} / {subtype.officialCode} {subtype.name}; "
                f"subtypeConfidence={subtype.confidence:.2f}"
            )

        prompt = f"""Выбери лучшую официальную пару "вид вопроса + subtype" для обращения.

Кандидаты уже валидны. Выбери ровно один key из списка:
{chr(10).join(lines)}

Логика для спорных случаев:
- Confidence важен: не переключайся с более уверенного questionType на альтернативный
  questionType только потому, что у альтернативы звучит подходящий subtype.
- Если top questionType заметно увереннее альтернативы, сохраняй его, если в тексте нет
  сильного официального признака другого вида.
- Не выбирай "Жалоба" только потому, что в тексте есть слова "жалоба", "нарушение", "незаконно" или "бездействие".
- Если основная просьба — провести проверку, принять меры, оказать содействие, устранить проблему или организовать работу органов, внимательно сравни с вариантом "Заявление".
- Если основной смысл — обжаловать конкретное решение/действие/бездействие, восстановить уже нарушенное право, отменить решение или снять незаконную обязанность/ответственность, внимательно сравни с вариантом "Жалоба".
- Выбирай пару целиком, а не subtype отдельно.

Жесткое правило, если среди кандидатов есть и 2 Заявление, и 3 Жалоба:
- 3 выбирай только если есть требование отменить конкретное решение/акт, восстановить нарушенное право, признать незаконным конкретное действие/бездействие или обжаловать конкретный отказ.
- 2 выбирай, если автор главным образом просит проверить, принять меры, устранить проблему, оказать содействие, организовать ремонт/выплату/услугу или решить конкретную ситуацию.
- Просьба "проверить", "принять меры", "устранить проблему", "разобраться", "провести проверку" обычно тянет к 2, даже если текст эмоциональный и содержит слово "жалоба".
- Массовая проблема или проблема группы людей/отрасли + просьба проверить, принять меры, разобраться, пресечь нарушение, оценить ущерб или компенсацию обычно тянет к 2. Для 3 нужно прямое требование отменить конкретный акт/решение или восстановить конкретное право.
- Жалобный стиль не равен виду 3. Для 3 нужен именно предмет обжалования: конкретное решение, отказ, действие или бездействие.
- Если questionType=2 и questionType=3 близки, но нет прямого требования отменить
  решение/акт, признать действие незаконным или восстановить конкретное право,
  выбирай пару с questionType=2.

Жесткое правило, если среди кандидатов есть и 2 Заявление, и 5 Запрос информации:
- 5 выбирай только если получение сведений, справки, порядка действий или разъяснения является самостоятельной конечной целью.
- 2 выбирай, если сведения нужны как часть решения конкретной жилищной, имущественной, социальной, медицинской, трудовой или иной жизненной проблемы заявителя.
- Формулировки "прошу сообщить", "прошу разъяснить", "кто является", "на каком основании" не делают вид 5 автоматически. Смотри, зачем автору сведения.

Few-shot логика сравнения пар:
- "Прошу помочь получить положенную субсидию/жилье" лучше 2 + 2.1.1, чем 3 + 3.1.1: автор просит содействие в реализации права, а не обжалует конкретное решение.
- "Прошу проверить незаконную свалку и принять меры" лучше 2 + 2.2.1/2.2.3, чем 3 + 3.2.1: автор сообщает о проблеме и просит проверку.
- "После ремонта дороги стало много пыли, жители просят принять меры" лучше 2 + 2.1.1/2.2.3, чем 3 + 3.2.1: это просьба решить проблему, а не обжалование конкретного решения.
- "Автобус не остановился на остановке, прошу разобраться" лучше 2 + 2.1.1, чем 2 + 2.2.3 или 3 + 3.2.1: основной смысл — содействие в решении конкретной ситуации.
- "Массово изъяли и уничтожили скот, авторы просят проверку, меры и оценку компенсации" лучше 2 + 2.2.x, чем 3 + 3.2.1, если нет требования отменить конкретное решение или восстановить конкретное право.
- "Жители и фермеры описывают массовый забой/изъятие скота, просят проверить законность действий служб, остановить практику, оценить компенсацию и принять меры" лучше 2 + 2.2.x, чем 3 + 3.2.1: это системное сообщение о нарушениях и просьба реагирования.
- "Родители и педагоги просят проверить спорное назначение директора школы и процедуру аттестации" лучше 2 + 2.2.x, чем 3 + 3.2.1, если нет прямого требования отменить приказ или восстановить конкретное личное право.
- "Работникам уже присуждена зарплата/есть исполнительные документы, но право на выплату не восстановлено; автор просит защитить это право" лучше 3 + 3.1.1/3.2.1, чем 2 + 2.2.x.
- "Прошу сообщить, кому передавалось жилье, чтобы решить вопрос проживания моей семьи" лучше 2 + 2.1.1, чем 5: сведения нужны для решения жилищной проблемы.
- "Прошу сообщить график приема и перечень документов" лучше 5: сведения являются самостоятельной целью.
- "Прошу отменить отказ администрации и восстановить мое право" лучше 3 + 3.1.1: есть конкретный отказ/решение и просьба восстановить нарушенное право.
- "Жалуюсь на бездействие должностного лица, из-за которого я не могу получить услугу" лучше 3 + 3.2.1/3.2.2: предмет — действие/бездействие должностного лица и нарушение/препятствие.
- Если две пары выглядят одинаково правдоподобно, выбирай ту, где subtype точнее описывает финальное требование автора, а не эмоциональный стиль текста.

Верни только JSON без markdown:
{{"key": "...", "confidence": 0.0, "reason": "кратко"}}

Текст обращения:
{text}"""
        try:
            payload = parse_json_response(self._llm(prompt))
            key = str(payload["key"])
            if key not in allowed_keys:
                raise ValueError("Unknown question pair key")
            for candidate in candidates:
                if candidate.key == key:
                    return candidate
        except Exception:
            return candidates[0]
        return candidates[0]
