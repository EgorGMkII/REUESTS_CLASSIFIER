        try:
            payload = parse_json_response(self._llm(prompt))
            candidates = payload.get("candidates")
            if not isinstance(candidates, list):
                # Backward-compatible parser for older mocks and provider drift.
                candidates = [payload]
            results: list[QuestionTypePrediction] = []
            seen: set[str] = set()
            for item in candidates:
                if not isinstance(item, dict):
                    continue
                prediction = _prediction_from_payload(item)
                if prediction.code in seen:
                    continue
                seen.add(prediction.code)
                results.append(prediction)
            if not results:
                raise ValueError("No valid question type candidates")
            if (
                k > 1
                and results[0].code in {"3", "5"}
                and results[0].confidence <= 0.9
                and "2" not in seen
            ):
                results.insert(
                    1,
                    QuestionTypePrediction(
                        code="2",
                        name=QUESTION_TYPES["2"],
                        confidence=0.35,
                        reason="Добавлено как обязательная альтернатива для спорного случая 2/3/5.",
                    ),
                )
            return results[:k]
        except Exception:
            return [item.model_copy() for item in _FALLBACK_LIST]
