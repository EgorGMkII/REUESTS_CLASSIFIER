        by_code = {candidate.code: candidate for candidate in candidates}
        try:
            payload = parse_json_response(self._llm(prompt))
            raw_themes = payload["themes"]
            if not isinstance(raw_themes, list):
                raise ValueError("themes must be an array")
            selected: list[ThemePrediction] = []
            seen: set[str] = set()
            diagnostics_selected: list[dict[str, object]] = []
            diagnostics_rejected: list[dict[str, object]] = []
            raw_rejected = payload.get("rejected", [])
            if isinstance(raw_rejected, list):
                for raw in raw_rejected:
                    if not isinstance(raw, dict):
                        continue
                    code = str(raw.get("code", ""))
                    if code not in by_code:
                        continue
                    diagnostics_rejected.append(
                        {
                            "code": code,
                            "role": "reject",
                            "matchQuality": str(raw.get("matchQuality", ""))[:50],
                            "reason": str(raw.get("reason", ""))[:500],
                        }
                    )
            for raw in raw_themes:
                if not isinstance(raw, dict):
                    continue
                code = str(raw.get("code", ""))
                if code in seen or code not in by_code:
                    continue
                role = str(raw.get("role", "core"))
                match_quality = str(raw.get("matchQuality", "exact"))
                diagnostic = {
                    "code": code,
                    "role": role[:50],
                    "matchQuality": match_quality[:50],
                    "reason": str(raw.get("reason", ""))[:500],
                }
                if role == "reject" or match_quality == "spurious":
                    diagnostics_rejected.append(diagnostic)
                    seen.add(code)
                    continue
                try:
                    confidence = valid_confidence(raw.get("confidence"))
                except (TypeError, ValueError):
                    continue
                candidate = by_code[code]
                selected.append(
                    ThemePrediction(
                        code=code,
                        name=candidate.name,
                        confidence=confidence,
                        section=candidate.section,
                    )
                )
                diagnostics_selected.append(diagnostic)
                seen.add(code)
                if len(selected) >= max_themes:
                    break
            self.last_diagnostics = {
                "selected": diagnostics_selected,
                "rejected": diagnostics_rejected,
            }
            if selected:
                return selected
        except Exception:
            pass
        fallback = _top_one(candidates[0])
        self.last_diagnostics = {
            "selected": [
                {
                    "code": fallback.code,
                    "role": "core",
                    "matchQuality": "fallback",
                    "reason": "ThemeSelector fallback to top retrieval candidate.",
                }
            ],
            "rejected": [],
        }
        return [fallback]
